/**
 * Wrap src/client.js into the module the DeepSeek Harness web client loads.
 *
 * The web client fetches a plugin's `exports["./client"]` file and evaluates it
 * with `window.__ModuleLoader__`, which calls the factory with a `require` that
 * resolves the host's React. So the build is one transformation: strip the ESM
 * `export ` prefixes and put the body inside that factory. No bundler and no
 * extra dependency, which keeps this package installable without a build step
 * on an end user's machine (`prepack` runs this before publish).
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'

const sourceUrl = new URL('../src/client.js', import.meta.url)
const outputUrl = new URL('../lib/client.js', import.meta.url)

const code = await readFile(sourceUrl, 'utf8')

if (/^\s*import\b/m.test(code)) {
  throw new Error('src/client.js must not import modules; take dependencies as arguments')
}

const body = code.replace(/^export (?=(?:const|function|let|var|class)\b)/gm, '')
if (/^\s*export\b/m.test(body)) {
  throw new Error('src/client.js has an export form this build script does not handle')
}

const built = `// Generated by scripts/build-client.mjs from src/client.js. Do not edit.
window.__ModuleLoader__.load({
  id: 'dsh-alibaba-mcp',
  factory: (require) => {
    const module = { exports: {} }
${indent(body, 4)}
    // The loader reads \`apply\` and \`inject\` off the factory result. \`inject\` is
    // the cordis service list that makes ctx.slots/ctx.locale exist at all.
    module.exports = Object.assign(createClient({ React: require('react') }), { inject })
    return module.exports
  },
})
`

await mkdir(new URL('../lib/', import.meta.url), { recursive: true })
await writeFile(outputUrl, built)
console.log(`built lib/client.js (${built.length} bytes)`)

function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text
    .split('\n')
    .map((line) => (line.trim() === '' ? '' : pad + line))
    .join('\n')
}
